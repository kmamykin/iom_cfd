"""Small helpers for reading/writing OpenFOAM files without OpenFOAM."""

from __future__ import annotations

import math
import re
from pathlib import Path
from typing import Any

import numpy as np

HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
| Generated by iomcfd. Edit the study YAML, not this file.                    |
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
// * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * * //

"""


def fmt(v: Any) -> str:
    """Format a Python value as an OpenFOAM token."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, np.integer)):
        return str(int(v))
    if isinstance(v, (float, np.floating)):
        return f"{float(v):.10g}"
    if isinstance(v, (list, tuple, np.ndarray)):
        return "(" + " ".join(fmt(x) for x in v) + ")"
    if isinstance(v, str):
        return v if re.fullmatch(r"[A-Za-z0-9_.:+\-()]+", v) else f'"{v}"'
    raise TypeError(f"cannot format {type(v)} for OpenFOAM")


def write_dict(
    path: Path,
    entries: dict[str, Any],
    obj: str | None = None,
    comments: dict[str, str] | None = None,
    preamble: str = "",
) -> None:
    """Write a flat dictionary of `key value;` entries (used for caseParameters)."""
    comments = comments or {}
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [HEADER.format(cls="dictionary", obj=obj or path.name) + preamble]
    width = max((len(k) for k in entries), default=10) + 2
    for k, v in entries.items():
        c = f"  // {comments[k]}" if k in comments else ""
        lines.append(f"{k:<{width}}{fmt(v)};{c}")
    path.write_text("\n".join(lines) + "\n")


def set_entry(path: Path, key: str, value: Any) -> None:
    """Replace a top-level `key value;` entry in an existing dictionary file."""
    path = Path(path)
    text = path.read_text()
    pat = re.compile(rf"^(\s*{re.escape(key)}\s+)[^;]*;", re.M)
    if not pat.search(text):
        raise KeyError(f"{key} not found in {path}")
    path.write_text(pat.sub(lambda m: f"{m.group(1)}{fmt(value)};", text, count=1))


