def read_dat(path: Path) -> tuple[list[str], np.ndarray]:
    """Read a postProcessing *.dat file -> (column names, data array).

    Handles '# Time  Cd  Cl ...' headers and vector values written as (x y z)
    (those columns are expanded to name_x, name_y, name_z).
    """
    names: list[str] = []
    rows: list[list[float]] = []
    for line in Path(path).read_text().splitlines():
        if line.startswith("#"):
            toks = line[1:].split()
            if toks and toks[0].lower() == "time":
                names = toks
            continue
        if not line.strip():
            continue
        vals = line.replace("(", " ").replace(")", " ").split()
        try:
            rows.append([float(v) for v in vals])
        except ValueError:
            continue
    if not rows:
        return names, np.empty((0, len(names)))
    width = min(len(r) for r in rows)
    data = np.array([r[:width] for r in rows])
    if len(names) != width:  # vector columns were expanded
        names = names[:1] + [f"c{i}" for i in range(1, width)]
    return names, data


def find_dat(case: Path, fo_name: str, file_name: str) -> list[Path]:
    """All postProcessing/<fo>/<startTime>/<file> (restarts create several)."""
    base = Path(case) / "postProcessing" / fo_name
    if not base.is_dir():
        return []
    out = []
    for d in sorted(base.iterdir(), key=lambda p: _time_key(p.name)):
        f = d / file_name
        if f.is_file():
            out.append(f)
    return out


def _time_key(name: str) -> float:
    try:
        return float(name)
    except ValueError:
        return math.inf


def latest_time(case: Path) -> str | None:
    times = []
    for d in Path(case).iterdir():
        if d.is_dir():
            try:
                times.append((float(d.name), d.name))
            except ValueError:
                pass
    return max(times)[1] if times else None


def read_text(path: Path) -> str:
    """A text file, or its gzipped copy `<path>.gz` (exported cases have
    gzipped logs and meshes). FileNotFoundError if neither exists."""
    path = Path(path)
    if path.is_file():
        return path.read_text(errors="replace")
    gz = path.with_name(path.name + ".gz")
    if gz.is_file():
        import gzip

        return gzip.decompress(gz.read_bytes()).decode(errors="replace")
    raise FileNotFoundError(path)


def tail_log(path: Path, n: int = 30) -> str:
    try:
        return "\n".join(read_text(path).splitlines()[-n:])
    except FileNotFoundError:
        return ""
